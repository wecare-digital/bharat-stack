/** Filter categories by a search term against category name + keywords. Empty term returns all. */
export function searchEmojiCategories ( term: string ): EmojiCategory[] {
    const q = term.trim().toLowerCase();
    if ( !q ) return EMOJI_CATEGORIES;
    return EMOJI_CATEGORIES.filter(
        c => c.name.toLowerCase().includes( q ) || c.keywords.includes( q )
    );
}
